const dictionaries: Record<Lang, Record<DictKey, string>> = { ar, en };

export function t(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  let text = dictionaries[lang][key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replace(`{${name}}`, String(value));
  }
  return text;
}

/** Action messages come back from server actions as keys (msg_*) or as raw text from parsers. */
export function actionMessage(lang: Lang, value: string): string {
  if (Object.hasOwn(ar, value)) return t(lang, value as DictKey);
  const key = `msg_${value}`;
  return Object.hasOwn(ar, key) ? t(lang, key as DictKey) : value;
}

export function dirOf(lang: Lang): "rtl" | "ltr" {
  return lang === "ar" ? "rtl" : "ltr";
}

export function isLang(value: string | undefined): value is Lang {
  return value === "ar" || value === "en";
}

/** Chooses the language: explicit cookie first, then the store default, then the browser's Accept-Language. */
export function resolveLang(cookieValue: string | undefined, storeDefault: "auto" | Lang, acceptLanguage: string | null): Lang {
  if (isLang(cookieValue)) return cookieValue;
  if (storeDefault !== "auto") return storeDefault;
  const first = (acceptLanguage ?? "").split(",")[0]?.trim().toLowerCase() ?? "";
  if (!first) return "ar"; // no browser hint: default to the primary audience
  return first.startsWith("ar") ? "ar" : "en";
}

